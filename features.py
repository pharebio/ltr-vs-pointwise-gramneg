"""
RDKit 2D normalized descriptor features for the LTR scaffold.

These are the 200 CDF-normalized RDKit descriptors (values in [0, 1], via
descriptastorus), stored as a parquet keyed by ``canonicalized_smiles``. They are the
``X`` for ``MLPScorer`` in the RankNet-vs-pointwise gate and for the capacity-matched
pointwise MLP / Random Forest baselines.

The parquet is not shipped (it is large); regenerate it from the public dataframe with:

    python compute_rdkit_features.py      # -> data/rdkit_features.parquet

Coverage is ~99.98% of the compounds; the handful of misses are RDKit descriptor
failures on exotic atoms (Se, organometallics, ...) and are returned via the ``found``
mask, which callers use to filter both X and their labels.
"""
from __future__ import annotations

import os
from functools import lru_cache

import numpy as np
import pandas as pd

FEATURES_PARQUET_NAME = "rdkit_features.parquet"

SMILES_COL = "canonicalized_smiles"
N_FEATURES = 200

_THIS_DIR = os.path.dirname(os.path.abspath(__file__))
DEFAULT_PARQUET = os.path.join(_THIS_DIR, "data", FEATURES_PARQUET_NAME)


@lru_cache(maxsize=2)
def load_feature_table(path: str | None = None) -> pd.DataFrame:
    """Load the feature parquet as a DataFrame indexed by canonicalized_smiles.

    ``path=None`` (default) resolves the parquet under ``data/`` (regenerated by
    ``compute_rdkit_features.py``). Pass an explicit ``path`` to load elsewhere.

    Cached: repeated calls with the same path reuse the in-memory table.
    Columns are the 200 ``rdkit_*`` descriptor names, dtype float32.
    """
    if path is None:
        from data_access import features_parquet
        path = features_parquet()
    if not os.path.exists(path):
        raise FileNotFoundError(
            f"RDKit feature parquet not found at {path}. "
            f"Regenerate it with:  python compute_rdkit_features.py"
        )
    table = pd.read_parquet(path)
    if table.index.name != SMILES_COL:
        if SMILES_COL in table.columns:
            table = table.set_index(SMILES_COL)
        else:
            raise ValueError(
                f"feature table has no '{SMILES_COL}' index or column; got "
                f"index={table.index.name!r}, columns[:3]={list(table.columns[:3])}"
            )
    # No hard width check: the RDKit parquet is 200-dim, but this loader is also
    # used for wider learned embeddings (e.g. 2048-dim CheMeleon). MLPScorer's
    # in_dim is set from X.shape[1] at call sites, so any width is fine.
    return table


def feature_names(path: str | None = None) -> list[str]:
    """The 200 descriptor column names (order matches the columns of ``align_features``)."""
    return list(load_feature_table(path).columns)


def align_features(
    smiles: list[str] | np.ndarray | pd.Series,
    table: pd.DataFrame | None = None,
    path: str | None = None,
    dtype=np.float32,
) -> tuple[np.ndarray, np.ndarray]:
    """Map a list of canonicalized SMILES to their RDKit feature rows.

    Returns
    -------
    X    : [n, 200] float array, row-aligned to ``smiles``. Rows for SMILES with
           no precomputed features are filled with NaN (see ``found``).
    found: [n] bool mask, True where features were available. Callers should
           filter both X and their labels/ids by this mask (only ~0.02% miss),
           e.g. ``X, y = X[found], y[found]``.

    The returned matrix is a copy; the cached table is never mutated.
    """
    if table is None:
        table = load_feature_table(path)
    smiles = pd.Index(np.asarray(smiles, dtype=object))
    # reindex preserves row order and inserts NaN rows for missing SMILES
    aligned = table.reindex(smiles)
    found = aligned.notna().all(axis=1).to_numpy()
    X = aligned.to_numpy(dtype=dtype)
    return X, found


MORGAN_RADIUS = 2      # RDKit radius = ECFP diameter/2, so radius 2 == ECFP4
MORGAN_N_BITS = 2048   # matches sali.morgan_fps, so similarity and model features agree


def morgan_features(
    smiles: list[str] | np.ndarray | pd.Series,
    radius: int = MORGAN_RADIUS,
    n_bits: int = MORGAN_N_BITS,
    dtype=np.uint8,
) -> tuple[np.ndarray, np.ndarray]:
    """Morgan (ECFP4) bit fingerprints as a dense matrix, row-aligned to ``smiles``.

    The fingerprint counterpart to ``align_features``: same ``(X, found)`` contract, so
    the two feature types are interchangeable at a call site. Unlike the RDKit
    descriptors these are computed on the fly (no parquet) -- fingerprints are cheap and
    depend on nothing but the SMILES.

    Returns
    -------
    X    : [n, n_bits] array of 0/1, row-aligned to ``smiles``. Rows for unparseable
           SMILES are left as zeros (see ``found``).
    found: [n] bool mask, True where RDKit could parse the SMILES. Filter both X and
           labels by it, exactly as with ``align_features``.

    ``dtype`` defaults to ``uint8`` deliberately: the full public subset is 828k x 2048,
    which is 1.7 GB as uint8 but 6.8 GB as float32. Cast per batch at the model boundary
    (sklearn/xgboost accept uint8; torch needs a float cast).

    Distinct SMILES are fingerprinted once and reused -- in long format the same compound
    recurs across assays, so the dedup is a large saving.
    """
    from rdkit import Chem, RDLogger
    from rdkit.Chem import rdFingerprintGenerator

    RDLogger.DisableLog("rdApp.*")  # parse failures are reported via `found`, not stderr
    smiles = np.asarray(smiles, dtype=object)
    gen = rdFingerprintGenerator.GetMorganGenerator(radius=radius, fpSize=n_bits)

    uniq, inverse = np.unique(smiles, return_inverse=True)
    U = np.zeros((len(uniq), n_bits), dtype=dtype)
    ok = np.zeros(len(uniq), dtype=bool)
    for i, s in enumerate(uniq):
        mol = Chem.MolFromSmiles(s) if isinstance(s, str) else None
        if mol is None:
            continue
        # GetFingerprintAsNumPy avoids materialising an ExplicitBitVect per molecule
        U[i] = gen.GetFingerprintAsNumPy(mol).astype(dtype, copy=False)
        ok[i] = True
    return U[inverse], ok[inverse]


if __name__ == "__main__":
    # Smoke check: coverage against the wide dataset.
    import argparse

    ap = argparse.ArgumentParser(description="Report RDKit feature coverage.")
    ap.add_argument(
        "--wide-csv",
        default=os.path.join(_THIS_DIR, "data", "public_gram_negative_wide_df.csv.gz"),
    )
    ap.add_argument("--parquet", default=DEFAULT_PARQUET)
    args = ap.parse_args()

    table = load_feature_table(args.parquet)
    print(f"feature table: {table.shape[0]:,} smiles x {table.shape[1]} features "
          f"(dtype {table.dtypes.iloc[0]})")
    print(f"first/last feature: {table.columns[0]} ... {table.columns[-1]}")

    wide = pd.read_csv(args.wide_csv, usecols=[SMILES_COL])
    X, found = align_features(wide[SMILES_COL], table=table)
    print(f"wide dataset: {len(wide):,} rows")
    print(f"aligned X: {X.shape}, found {found.sum():,}/{len(found):,} "
          f"({100 * found.mean():.2f}%), missing {(~found).sum():,}")
