"""Which ClearML task produced the result currently on disk, for every config.

A ``run_id`` hashes only (scope, split, arch, features, loss, seed), so it is deliberately
STABLE across re-runs -- re-running after a bug fix reuses the id and overwrites the JSON.
That is what makes the results directory resumable, but it also means the id alone cannot
tell you which task, commit, or code version a given number came from. Several configs
here have already been run more than once (the lambdaloss hyperparameter-threading fix,
the lambdamart pair-budget fix), so the distinction is not hypothetical.

run_benchmark records clearml_task_id / git_commit / finished_utc in each result; this
regenerates the index from those, so it cannot drift from the data.

    micromamba run -n learn2rank python make_task_index.py
    micromamba run -n learn2rank python make_task_index.py --out results/task_index.md
"""
from __future__ import annotations

import argparse
import glob
import json
import os
from pathlib import Path

RESULTS = "results/benchmark/*.json"
OUT = "results/task_index.md"
UI = "https://app.clear.ml/projects/*/experiments"


def collect(pattern: str = RESULTS) -> list[dict]:
    rows = []
    for p in sorted(glob.glob(pattern)):
        with open(p) as fh:
            r = json.load(fh)
        # skip non-result JSONs living in the same dir (e.g. bootstrap_ci_cache.json)
        if not isinstance(r, dict) or "config" not in r:
            continue
        c = r.get("config", {})
        rows.append({
            "run_id": r.get("run_id", Path(p).stem),
            "status": r.get("status", "?"),
            "arch": c.get("arch"), "features": c.get("features"), "loss": c.get("loss"),
            "scope": c.get("scope"), "split": c.get("split"),
            "bedroc": r.get("aggregate", {}).get("bedroc"),
            "task": r.get("clearml_task_id"),
            "commit": r.get("git_commit"),
            "finished": r.get("finished_utc"),
        })
    return rows


def backfill(pattern: str = RESULTS) -> int:
    """Attach task ids to results written before provenance recording existed.

    Every tracked run names its task ``bench_<run_id>``, so the id is recoverable from
    ClearML. Where a config was run more than once we take the LATEST task, which is the
    one whose output overwrote the JSON. Writes the id into the result file so the index
    stays derived from the data rather than from a live query.
    """
    from clearml import Task

    n = 0
    for p in sorted(glob.glob(pattern)):
        with open(p) as fh:
            r = json.load(fh)
        if r.get("clearml_task_id"):
            continue
        rid = r.get("run_id", Path(p).stem)
        try:
            tasks = Task.get_tasks(project_name=os.environ.get(
                                       "LEARN2RANK_CLEARML_PROJECT", "learn2rank"),
                                   task_name=f"^bench_{rid}$")
        except Exception as e:  # noqa: BLE001
            print(f"  lookup failed for {rid}: {type(e).__name__}: {e}")
            continue
        if not tasks:
            continue
        latest = sorted(tasks, key=lambda t: str(t.data.created))[-1]
        r["clearml_task_id"] = latest.id
        r.setdefault("provenance_note", "task id backfilled by make_task_index.py")
        with open(p, "w") as fh:
            json.dump(r, fh, indent=1, default=str)
        n += 1
    return n


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=OUT)
    ap.add_argument("--results", default=RESULTS)
    ap.add_argument("--backfill", action="store_true",
                    help="look up task ids in ClearML for results that predate provenance")
    a = ap.parse_args()

    if a.backfill:
        print(f"backfilled {backfill(a.results)} result(s)")
    rows = collect(a.results)
    missing = [r for r in rows if not r["task"]]

    lines = [
        "# Benchmark result -> ClearML task index",
        "",
        "Generated by `make_task_index.py` from the result JSONs -- do not edit by hand.",
        "",
        f"{len(rows)} results, {len(rows) - len(missing)} with a recorded task id.",
        "",
        "`run_id` is stable across re-runs (it hashes only the config), so a config that "
        "was re-run after a fix keeps its id and its JSON is overwritten. The task id and "
        "commit below identify the run that produced the number currently on disk.",
        "",
        "| run_id | arch | features | loss | scope | split | BEDROC | commit | ClearML task |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in sorted(rows, key=lambda x: (str(x["scope"]), str(x["split"]), str(x["arch"]))):
        b = f"{r['bedroc']:.3f}" if isinstance(r["bedroc"], float) else "-"
        lines.append(
            f"| `{r['run_id']}` | {r['arch']} | {r['features']} | {r['loss']} | "
            f"{r['scope']} | {r['split']} | {b} | {r['commit'] or '-'} | "
            f"{r['task'] or '_(local, untracked)_'} |")

    if missing:
        lines += ["", f"## {len(missing)} result(s) with no task id", "",
                  "Produced before provenance recording, or run without `--log_to_clearml`.",
                  "Re-run with tracking to attach one.", ""]
        lines += [f"- `{r['run_id']}`" for r in missing]

    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out).write_text("\n".join(lines) + "\n")
    print(f"wrote {a.out}: {len(rows)} results, {len(missing)} missing a task id")


if __name__ == "__main__":
    main()
